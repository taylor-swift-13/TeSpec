#!/usr/bin/env python3
"""Validate archived evidence and regenerate the manuscript's result tables.

This reanalyses recorded results. It does not rerun executors or proof search.
"""
from collections import Counter, defaultdict
import hashlib
import gzip
import json
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parent


def read(path):
    return json.loads(path.read_text())


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def source(path):
    return {"path": str(path.relative_to(ROOT)), "sha256": sha(path)}


def table(name, caption, label, columns, header, rows, note=""):
    body = "\n".join(" & ".join(row) + r" \\" for row in rows)
    text = (
        "% Generated by scripts/summarize-evidence.py; edit the generator.\n"
        "\\begin{table}[t]\n\\centering\\small\n"
        + "\\caption{" + caption + "}\n\\label{" + label + "}\n"
        + "\\begin{tabular}{" + columns + "}\n\\toprule\n"
        + " & ".join(header) + r" \\" + "\n\\midrule\n" + body
        + "\n\\bottomrule\n\\end{tabular}\n"
        + ("\\par\\smallskip\\parbox{\\columnwidth}{\\footnotesize " + note + "}\n" if note else "")
        + "\\end{table}\n"
    )
    (PAPER / "tables" / name).write_text(text)


def check_case_study_receipts():
    base = PAPER / "evidence/comparative-case-studies-20261013"
    archive = read(base / "archive-index.json")
    for entry in archive["files"]:
        target = ROOT / entry["path"]
        assert target.resolve().is_relative_to(base.resolve())
        assert sha(target) == entry["sha256"], target
    paths = [base / "evidence/least-root-20261013/receipt.json",
             base / "case-studies/divisibility/evidence/receipt.json",
             base / "case-studies/divisibility/theory/receipt.json",
             base / "case-studies/shared-oracle-controls/receipt.json"]
    receipts = []
    omitted_caches = []
    for path in paths:
        record = read(path)
        for name, expected in record["files"].items():
            target = (path.parent / name).resolve()
            assert target.is_relative_to(path.parent.resolve()), name
            if target.is_file():
                assert sha(target) == expected, (path, name)
            else:
                assert target.name in (".lia.cache", ".nia.cache"), (path, name)
                omitted_caches.append({"path": str(target.relative_to(ROOT)), "original_sha256": expected})
        receipts.append(record)
    root, division, rewrite, controls = receipts
    assert root["itp_result"] == "PASS" and root["audited_original_goals"] == 26
    assert root["kernel_exit_code"] == 0
    assert len(division["cases"]) == 2
    assert all(row["status"] == "PASS" and row["original_vcs"] == 6
               for row in division["cases"])
    assert rewrite["coqchk_exit_code"] == 0 and rewrite["assumptions"] == []
    assert controls["coins"]["coqchk_exit_code"] == 0
    assert controls["verina_relation"]["lean_exit_code"] == 0
    assert controls["verina_relation"]["sorryAx_present"] is False
    return {"scope": "2026-10-13 checked receipts; C certificates and pure oracle controls separately",
            "sources": [source(path) for path in paths],
            "omitted_regenerable_caches": omitted_caches,
            "archived_files_hash_checked": len(archive["files"]),
            "c_positive_groups": 3, "c_original_vcs": [26, 6, 6],
            "pure_oracle_positive_pairs": 11, "pure_oracle_rejected_pairs": 4,
            "verina_full_pipeline_run": False, "coins_full_pipeline_run": False}


def main():
    archive = PAPER / "evidence/paired"
    pair_file = archive / "results.json"
    paired = read(pair_file)
    for name, expected in paired["files"].items():
        path = archive / name
        assert path.is_relative_to(archive) and sha(path) == expected, name
    grouped = defaultdict(set)
    for row in paired["observations"]:
        log = archive / row["evidence"]
        assert log.is_file(), log
        assert any(sha(p) == row["source_sha256"] for p in log.parent.glob("*.c")), row
        if row["tool"] == "tespec":
            report = read(log.parent / "tespec-report.json")
            assert len(report["results"]) == 1
            actual = report["results"][0]
            assert actual["status"] == row["status"], row
            assert actual["phases"] == row["phases"], row
        grouped[(row["subject"], row["tool"], row["variant"])].add(row["status"])
    assert all(len(values) == 1 for values in grouped.values()), "mode-dependent outcomes need separate rows"
    names = {"VERIFIED": "V", "UNPROVED": "U", "RUNTIME_PASS": "P", "RUNTIME_VIOLATION": "F", "PASS": "P", "UNKNOWN": "U"}
    rows = []
    for subject in paired["subjects"]:
        values = []
        for tool in ["cn_verify", "fulminate", "tespec"]:
            values.append(" / ".join(names[next(iter(grouped[(subject, tool, v)]))] for v in ["valid", "wrong_post"]))
        rows.append([subject.replace("_", r"\_"), *values])
    table("paired-summary.tex", "Paired subjects: valid / mutated contract outcomes.", "tab:paired",
          "lccc", ["Subject", "CN", "Fulminate", "TeSpec"], rows,
          "V: verified; P: pass; F: runtime violation; U: unproved or unknown. "
          "CN checks full domains, Fulminate concrete fixtures, and TeSpec bound symbolic domains. "
          "The 11 contract configurations cover 10 body families; repeated modes are collapsed.")
    e2e_file = PAPER / "executor-e2e-results.json"
    e2e = read(e2e_file)["summary"]
    assert sum(e2e["verdicts"].values()) == e2e["total"]
    table("regression-summary.tex", "Development regression outcomes (1,322 runs).", "tab:regression",
          "lrl", ["Verdict", "Runs", "Interpretation"],
          [[key, str(e2e["verdicts"][key]), desc] for key, desc in [
              ("PASS", "Recorded checks discharged"), ("UNKNOWN", "Unresolved or incomplete"),
              ("ERROR", "Execution/coverage diagnostic"), ("INVALID", "Empty entry domain")]],
          "All recorded expectations are met. Negative checks include deliberately unsupported cases; "
          "expectation agreement is distinct from confirmed violation detection.")
    corpus_file = PAPER / "instance-semantics-evaluation.json"
    corpus = read(corpus_file)["corpus"]
    assert sum(corpus["summary"][k] for k in ["PASS", "UNKNOWN", "INVALID", "ERROR"]) == corpus["runs"]
    baseline_file = PAPER / "evidence/least-root-baselines/report.json"
    baseline = read(baseline_file)
    for run in baseline["runs"]:
        directory = baseline_file.parent / (run["variant"] + "-" + run["engine"])
        log = gzip.decompress((directory / "execution.log.gz").read_bytes())
        assert hashlib.sha256(log).hexdigest() == run["log_sha256"]
        source_file = baseline_file.parent / ("subject.cn.c" if run["variant"] == "original" else "subject.finite.cn.c")
        assert sha(source_file) == run["source_sha256"]
        if run["variant"] == "original":
            assert b"Cannot infer upper bound" in log and run["returncode"] != 0
        elif run["engine"] == "fulminate":
            assert run["returncode"] == 0
    alias_file = PAPER / "evidence/audits/local-alias.json"
    aliases = read(alias_file)
    counts = {v: dict(Counter(r["status"] for r in aliases if r["version"] == v)) for v in ["before", "after"]}
    assert len(aliases) == 48 and len({r["case"] for r in aliases}) == 12
    assert counts == {"before": {"UNKNOWN": 24}, "after": {"PASS": 12, "UNKNOWN": 12}}
    proj_file = PAPER / "evidence/audits/projection.json"
    proj = read(proj_file)
    assert proj["new_overall_passes"] == 0
    for case in proj["paired_cases"]:
        assert len(case["before"]["root_residual_goals"]) == 2
        assert len(case["pure_projection"]["root_residual_goals"]) == 1
    quant_file = PAPER / "evidence/audits/quantified-pair.json"
    quant = read(quant_file)
    assert quant["cases"]["positive"]["final_status"] == "PASS"
    assert quant["cases"]["negative"]["certificate_status"] == "VC_REFUTED"
    assert quant["negative_execution_counterexample"].startswith("NOT_ESTABLISHED")
    proof_index = PAPER / "evidence/proof-cases/index.json"
    proof_rows, proof_summaries = [], []
    for case in read(proof_index):
        folder = proof_index.parent / case["id"]
        for name, expected in case["files"].items():
            assert sha(folder / name) == expected, (case["id"], name)
        report = read(folder / "certificate-report.json")
        manifest = read(folder / "manifest.json")
        assert report["original_goal_sha256"] == sha(folder / "Goal.v")
        assert report["candidate_sha256"] == sha(folder / "Candidate.v")
        count = len(manifest["goals"])
        assert report["assumptions_audited_goals"] == count
        result = {"PASS": "Proved", "VC_REFUTED": "Refuted VC"}[report["status"]]
        proof_rows.append([case["label"], str(count), result, f'{report["duration_seconds"]:.2f}'])
        proof_summaries.append({"case": case["id"], "goals": count,
                                "status": report["status"], "seconds": report["duration_seconds"]})
    table("proof-summary.tex", "Independent checking of complete original VC groups.", "tab:proofs",
          "@{}lrcr@{}", ["Case", "VCs", "Evidence", "Check (s)"], proof_rows,
          "Time includes certificate compilation, assumption audit, and kernel replay. "
          "These are separate archived runs; construction time is excluded. "
          "The mutant proves one VC's negation and the other 26 original obligations.")
    table("mechanism-summary.tex", "Mechanism probes separate complete results from local proof progress.", "tab:mechanisms",
          r"p{.30\columnwidth}p{.59\columnwidth}", ["Mechanism", "Observed change"], [
              ["Local witness resolution", "12 valid-mode runs: U $\\to$ P; 12 incorrect-mode runs: U $\\to$ U"],
              ["Checked pure facts", "Two configurations: 2 $\\to$ 1 residual roots each; 0 new complete passes"],
              ["Full proof completion", "Positive least-root: U $\\to$ P, all 27 obligations checked"],
              ["VC refutation", "Intermediate mutant: checked VC refutation; reachable violation unestablished"]])
    summary = {
        "schema": "tespec-paper-evidence/v1",
        "scope": "reanalysis of archived observations, not new executor measurements",
        "sources": [source(p) for p in [pair_file, e2e_file, corpus_file, alias_file, proj_file, quant_file, proof_index, baseline_file]],
        "paired": {"invocations": len(paired["observations"]), "subjects": len(paired["subjects"]),
                   "distinct_body_families": 10, "validated_files": len(paired["files"]),
                   "valid_tespec": dict(Counter(next(iter(grouped[(s, "tespec", "valid")])) for s in paired["subjects"])),
                   "mutated_tespec": dict(Counter(next(iter(grouped[(s, "tespec", "wrong_post")])) for s in paired["subjects"]))},
        "regressions": e2e,
        "local_observations": counts,
        "quantified_pair": quant["cases"],
        "projection_new_complete_passes": proj["new_overall_passes"],
        "proof_groups": proof_summaries,
        "comparative_case_studies": check_case_study_receipts(),
        "corpus": {k: corpus[k] for k in ["source_count", "specs_selected", "summary", "runs", "binding_policy"]},
    }
    (PAPER / "evidence-summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary["paired"], indent=2))


if __name__ == "__main__":
    main()
