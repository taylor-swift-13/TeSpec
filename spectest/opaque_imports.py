"""Read compiled name inventories for ordinary, notation-free Gallina libraries."""

from functools import lru_cache
from pathlib import Path
from tempfile import TemporaryDirectory
import hashlib
import os
import shutil
import re
import subprocess

from .core import _coq_dependency_code
from .certificates import strip_comments

_IDENT = r"[A-Za-z_][A-Za-z0-9_']*"
_STANDARD = {"ZArith", "List", "Lia", "Program.Wf"}


def passive_declarations(source):
    """Reject imports, exports or declarations that can change the query language."""
    text = strip_comments(source)
    if '"' in text or re.search(
        r"[:#]>|#\[|\b(?:where|ltac|ltac2|with_definition)\b", text
    ):
        return set()
    code = _coq_dependency_code(text)
    names = set()
    proof = False
    for part in re.split(r"\.(?=\s|$)", code):
        cmd = " ".join(part.split())
        if not cmd:
            continue
        if proof:
            if cmd == "Qed":
                proof = False
            elif not all(
                re.fullmatch(
                    r"(?:try )?(?:Proof|fix|intros?|simpl|lia|specialize|destruct|unfold|pose proof|"
                    r"WfExtensionality\.unfold_sub|rewrite|reflexivity)(?: [\w ()'|:\[\]*]+)?",
                    step.strip(),
                )
                for step in cmd.split(";")
            ):
                return set()
            continue
        imported = re.fullmatch(r"From Coq Require Import ([\w. ]+)", cmd)
        if imported and set(imported[1].split()) <= _STANDARD:
            continue
        if cmd in {
            "Import ListNotations",
            "Open Scope Z_scope",
            "Local Open Scope Z_scope",
        }:
            continue
        if cmd == "Next Obligation":
            proof = True
            continue
        decl = re.fullmatch(
            r"(Lemma|Theorem|Definition|(?:Program )?Fixpoint) (" + _IDENT + r")\b(.+)",
            cmd,
        )
        if not decl:
            return set()
        if decl[1] in {"Lemma", "Theorem"}:
            proof = ":=" not in decl[3]
        elif ":=" not in decl[3]:
            return set()
        names.add(decl[2])
    return set() if proof else names


def compiled_interface(module, source, build, compiler_args):
    declared = passive_declarations(source)
    if not declared:
        return None
    # Print Module includes names generated by Program (not just source names).
    unit = build / "TeSpecInspectOpaqueImports.v"
    if unit.exists():
        return None
    unit.write_text(
        f"From Coq Require Import ZArith List.\nRequire {module}.\nSet Printing Width 100000.\nPrint Module {module}.\n"
    )
    try:
        result = subprocess.run(
            [*compiler_args, str(unit)],
            cwd=build,
            capture_output=True,
            text=True,
            timeout=30,
        )
    except subprocess.TimeoutExpired:
        return None
    finally:
        unit.unlink()
    if result.returncode:
        return None
    signature = re.fullmatch(
        r"\s*Module\s+" + re.escape(module) + r"\s*:=\s*Struct\s+(.*?)\s+End\s*",
        result.stdout,
        re.S,
    )
    if not signature:
        return None
    names = []
    signatures = {}
    for entry in re.split(r"\.(?=\s|$)", signature[1]):
        if entry.strip():
            match = re.fullmatch(
                r"(Definition|Parameter)\s+(" + _IDENT + r")\s*:\s*(.+)",
                entry.strip(),
                re.S,
            )
            if not match:
                return None
            kind, name, typ = match.groups()
            names.append(name)
            signature = [" ".join(t.split()) for t in typ.split("->")]
            if (
                kind == "Definition"
                and name in declared
                and 2 <= len(signature) <= 9
                and set(signature) <= {"Z", "list Z"}
            ):
                signatures[name] = signature
    if len(names) != len(set(names)) or not declared <= set(names):
        return None
    inventory = sorted(names)
    result = {
        "source_sha256": hashlib.sha256(source.encode()).hexdigest(),
        "exports": inventory,
        "exports_sha256": _inventory_digest(inventory),
    }
    if signatures:
        obj = build.joinpath(*module.split(".")).with_suffix(".vo")
        result["ground_signatures"] = signatures
        result["object_sha256"] = hashlib.sha256(obj.read_bytes()).hexdigest()
    return result


def original_interface(module, raw, vc):
    """Inspect an unchanged auxiliary module even when no layout override was selected."""
    if (not re.fullmatch(_IDENT + r"(?:\." + _IDENT + ")*", module)
            or len(raw) > 262144
            or any(d["module"].split(".")[0] in {"Coq", "Stdlib"}
                   for group in ("coq_dependencies", "runtime_dependencies", "generated_coq_dependencies")
                   for d in vc.get(group, []))):
        return None
    compiler = os.environ.get("COQC") or shutil.which("coqc")
    if not compiler:
        return None
    return _compiled_original(module, raw, compiler)


@lru_cache(maxsize=32)
def _compiled_original(module, raw, compiler):
    source = raw.decode("utf-8")
    if not passive_declarations(source):
        return None
    with TemporaryDirectory(prefix="tespec-opaque-") as tmp:
        work = Path(tmp)
        unit = work.joinpath(*module.split(".")).with_suffix(".v")
        unit.parent.mkdir(parents=True, exist_ok=True)
        unit.write_bytes(raw)
        cmd = [compiler, "-q", "-Q", str(work), ""]
        limiter = shutil.which("prlimit")
        if limiter:
            cmd = [limiter, "--as=1073741824", "--fsize=67108864", "--", *cmd]
        try:
            result = subprocess.run([*cmd, str(unit)], cwd=work, stdout=subprocess.DEVNULL,
                                    stderr=subprocess.DEVNULL, timeout=5)
            if result.returncode == 0:
                return compiled_interface(module, source, work, cmd)
        except (OSError, subprocess.TimeoutExpired):
            pass
    return None


def _inventory_digest(names):
    return hashlib.sha256("\n".join(names).encode()).hexdigest()


def checked_names(source, record):
    raw = source.decode()
    declared = passive_declarations(raw)
    if (
        not isinstance(record, dict)
        or not declared
        or record.get("source_sha256") != hashlib.sha256(source).hexdigest()
    ):
        raise ValueError("different_opaque_import_source")
    names = record.get("exports")
    if (
        not isinstance(names, list)
        or not all(isinstance(n, str) and re.fullmatch(_IDENT, n) for n in names)
        or sorted(set(names)) != names
        or not declared <= set(names)
        or record.get("exports_sha256") != _inventory_digest(names)
    ):
        raise ValueError("invalid_opaque_import_inventory")
    return names
